function getMyHome(user_id,nome)                                        --########## Verificar se a casa é do cidadão ##########
    for k,v in pairs(casas_config) do
        if string.sub(nome,0,6) == k or string.sub(nome,0,2) == k then
            vRP._prepare("vRP/get_homeuser","SELECT * FROM vrp_homes_permissions WHERE user_id = @user_id AND home = @home")
            local myHomes = vRP.query("vRP/get_homeuser",{ user_id = parseInt(user_id), home = tostring(nome) })
            if myHomes[1] ~= nil then
                return true, v
            end
        end
    end
end

function garagePayment(source,payment)                                  --########## Pagamento da garagem ##########
    local user_id = vRP.getUserId(source)
	if vRP.request(source,"Deseja alugar o veiculo por R$"..payment.."?",30) then
        if Config.base == "creative" then
            return vRP.paymentBank(parseInt(user_id),payment)
        elseif Config.base == "vrpex" then
            return vRP.tryFullPayment(parseInt(user_id),payment)
        end
    end
end

function checkArrestedVehicle(source,user_id,data,vname)                --########## Verifica se o veiculo está detido ou com multa ##########
    if Config.base == "vrpex" then
        local valordetido = 7/100
        -- if parseInt(data.detido) == 1 or parseInt(os.time()) <= parseInt(data.time+24*60*60) then
        if parseInt(data.detido) == 3 then
            TriggerClientEvent("Notify",source,"negado","Veiculo está apreendido no Pátio",5000)
        elseif (parseInt(data.detido) == 1 or parseInt(data.detido) == 2) and parseInt(os.time()) <= parseInt(data.time+24*60*60) then
            if vRP.vehicleType(tostring(vname)) == "cars" or vRP.vehicleType(tostring(vname)) == "bikes" or vRP.vehicleType(tostring(vname)) == nil then
                valordetido = 3/100
            elseif vRP.vehicleType(tostring(vname)) == "donate" then
                valordetido = 5/100
            end
            local status = vRP.request(source,"O veículo "..vname.." está detido, deseja acionar o seguro pagando <b>R$"..vRP.format(parseInt(vRP.vehiclePrice(vname)*valordetido)).."</b>?",60)
            if status then
                if vRP.tryFullPayment(user_id,parseInt(vRP.vehiclePrice(vname)*valordetido)) then
                    vRP._prepare("will/set_detido","UPDATE vrp_user_vehicles SET detido = @detido AND time = @time WHERE user_id = @user_id AND vehicle = @vehicle")
                    vRP.execute("will/set_detido",{ user_id = parseInt(user_id), vehicle = vname, detido = 0, time = 0 })
                    return true
                else
                    TriggerClientEvent("Notify",source,"negado","Dinheiro insuficiente.",5000)
                    return false
                end
            end
        else
            return true
        end
    elseif Config.base == "creative" then
        local valordetido = 2/100
        if parseInt(data.arrest) >= 1 or parseInt(os.time()) <= parseInt(data.time+24*60*60) then
            if vRP.vehicleType(tostring(vname)) == "cars" or vRP.vehicleType(tostring(vname)) == "bikes" or vRP.vehicleType(tostring(vname)) == nil then
                valordetido = 3/100
            elseif vRP.vehicleType(tostring(vname)) == "donate" then
                valordetido = 5/100
            end
            local status = vRP.request(source,"O veículo "..vname.." está detido, deseja acionar o seguro pagando <b>R$"..vRP.format(parseInt(vRP.vehiclePrice(vname)*valordetido)).."</b>?",60)
            if status then
                if vRP.paymentBank(user_id,parseInt(vRP.vehiclePrice(vname)*valordetido)) then
                    vRP._prepare("will/set_arrest","UPDATE vrp_user_vehicles SET arrest = @arrest AND time = @time WHERE user_id = @user_id AND vehicle = @vehicle")
                    vRP.execute("will/set_arrest",{ user_id = parseInt(user_id), vehicle = vname, arrest = 0, time = 0 })
                    return true
                else
                    TriggerClientEvent("Notify",source,"negado","Dinheiro insuficiente.",5000)
                    return false
                end
            end
        else
            return true
        end
    end
end

