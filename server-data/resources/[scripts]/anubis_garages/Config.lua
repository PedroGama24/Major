function vehicleToLock(user_id)
    local source = vRP.getUserSource(user_id)
    if user_id and Config.use_vehicle_lock then
		local vehicle,vehNet,vehPlate,vehName,vehLock = vRPclient.vehList(source,4)
		if vehicle and vehPlate then
			local identity = vRP.getUserIdentity(user_id)
			local plateUserId = 0
			if Config.base == "creative" then
				plateUserId =  vRP.getVehiclePlate(vehPlate) or vRP.getUserIdRegistration(vehPlate)
			elseif Config.base == "vrpex" then
				plateUserId = vRP.getUserByRegistration(vehPlate)
			end

            if user_id == plateUserId or vehPlate == identity.registration then
                if not vCLIENT.inVehicle(source) then
                    if Config.base == "creative" then
                        vRPclient.playAnim(source, true,{"anim@mp_player_intmenu@key_fob@","fob_click"},false)
                    elseif Config.base == "vrpex" then
                        vRPclient.playAnim(source, true,{{"anim@mp_player_intmenu@key_fob@","fob_click"}},false)
                    end
                    Citizen.Wait(400)
                    vRPclient._stopAnim(source)
                end
                if vehLock == 2 or vehLock == 0 then
                    TriggerClientEvent("Notify",source,"importante","Veículo <b>destrancado</b> com sucesso.",5000)
                    TriggerClientEvent("vrp_sound:source",source,"unlock",0.4)
                else
                    TriggerClientEvent("Notify",source,"importante","Veículo <b>trancado</b> com sucesso.",5000)
                    TriggerClientEvent("vrp_sound:source",source,"lock",0.3)
                end
				TriggerClientEvent("will_garages:vehicleClientLock",-1,vehNet,vehLock)
			end
		end
	end
end

